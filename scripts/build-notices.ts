/**
 * Builds app/public/THIRD_PARTY_NOTICES.txt: the licence texts of the runtime
 * dependency tree of app/package.json. Started with `npm run build:notices`.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export interface LicenceFile {
  readonly fileName: string;
  readonly text: string;
}
export interface NoticePackage {
  readonly name: string;
  readonly version: string;
  readonly licence: string;
  readonly files: readonly LicenceFile[];
}

/** A font that is not installed through npm. Its licence text is read from the repository. */
export interface FontNotice {
  readonly name: string;
  readonly release: string;
  readonly licence: string;
  readonly source: string;
  readonly text: string;
}

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The fonts that are not npm packages, with the verbatim licence file from data/raw/fonts. */
export function repoFontNotices(root: string = REPO_ROOT): FontNotice[] {
  return [
    {
      name: 'LXGW WenKai Regular',
      release: 'v1.530',
      licence: 'SIL Open Font License 1.1',
      source: 'data/raw/fonts/lxgw-wenkai/OFL.txt',
      text: readFileSync(join(root, 'data', 'raw', 'fonts', 'lxgw-wenkai', 'OFL.txt'), 'utf8'),
    },
  ];
}

const LICENCE_FILE = /^(licen[cs]e|copying)(\..*)?$/i;
const RULE = '='.repeat(80);

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function readJson(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>;
}

function depNames(pkg: Record<string, unknown>): string[] {
  const names: string[] = [];
  for (const key of ['dependencies', 'optionalDependencies']) {
    const block = pkg[key];
    if (block && typeof block === 'object') names.push(...Object.keys(block));
  }
  return names;
}

/** Resolve like Node: node_modules of the requiring dir, then each parent. */
function resolvePackageDir(name: string, fromDir: string): string | null {
  let dir = resolve(fromDir);
  for (;;) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function readLicenceFiles(dir: string): LicenceFile[] {
  return readdirSync(dir)
    .filter((f) => LICENCE_FILE.test(f) && statSync(join(dir, f)).isFile())
    .sort(compare)
    .map((fileName) => ({ fileName, text: readFileSync(join(dir, fileName), 'utf8') }));
}

export function collectRuntimePackages(appDir: string): NoticePackage[] {
  const root = resolve(appDir);
  const found = new Map<string, NoticePackage>();
  const visit = (names: string[], fromDir: string): void => {
    for (const name of names) {
      const dir = resolvePackageDir(name, fromDir);
      if (!dir) throw new Error(`Package ${name} is not installed (required from ${fromDir.split(/[\\/]/).pop()})`);
      const pkg = readJson(join(dir, 'package.json'));
      const version = String(pkg.version ?? '');
      const key = `${name}@${version}`;
      if (found.has(key)) continue;
      const licence = pkg.license;
      if (typeof licence !== 'string' || licence === '') {
        throw new Error(`Package ${name} has no "license" identifier in its package.json`);
      }
      const files = readLicenceFiles(dir);
      if (files.length === 0) throw new Error(`Package ${name} has no licence file`);
      found.set(key, { name, version, licence, files });
      visit(depNames(pkg), dir);
    }
  };
  visit(depNames(readJson(join(root, 'package.json'))), root);
  return [...found.values()].sort((a, b) => compare(a.name, b.name) || compare(a.version, b.version));
}

export function renderNotices(
  packages: readonly NoticePackage[],
  fonts: readonly FontNotice[] = repoFontNotices(),
): string {
  const sorted = [...packages].sort((a, b) => compare(a.name, b.name) || compare(a.version, b.version));
  let out =
    'Third-party notices for the runtime dependencies of Ghost Script.\n' +
    'Generated by scripts/build-notices.ts. Do not edit by hand.\n';
  for (const p of sorted) {
    for (const f of [...p.files].sort((a, b) => compare(a.fileName, b.fileName))) {
      out += `\n${RULE}\n${p.name} ${p.version}\nLicence: ${p.licence}\nFile: ${f.fileName}\n${RULE}\n`;
      out += f.text.endsWith('\n') ? f.text : `${f.text}\n`;
    }
  }
  if (fonts.length > 0) {
    out += `\n${RULE}\nFonts not installed through npm\n${RULE}\n`;
    for (const f of [...fonts].sort((a, b) => compare(a.name, b.name))) {
      out += `\n${RULE}\nFont: ${f.name}, release ${f.release}\nFont licence: ${f.licence}\nFile: ${f.source}\n${RULE}\n`;
      out += f.text.endsWith('\n') ? f.text : `${f.text}\n`;
    }
  }
  return out;
}

export function runtimeSummary(
  packages: readonly NoticePackage[],
): { name: string; version: string; licence: string }[] {
  return [...packages]
    .sort((a, b) => compare(a.name, b.name) || compare(a.version, b.version))
    .map(({ name, version, licence }) => ({ name, version, licence }));
}

function main(): void {
  const root = REPO_ROOT;
  let text: string;
  try {
    text = renderNotices(collectRuntimePackages(join(root, 'app')));
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
  writeFileSync(join(root, 'app', 'public', 'THIRD_PARTY_NOTICES.txt'), text);
  console.log('Wrote app/public/THIRD_PARTY_NOTICES.txt');
}

// ESM-safe execution guard: run main() only when executed directly.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
