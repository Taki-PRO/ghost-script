// Prompt counts (pure). Counts how many ghost clues of levels 2 and 3 a human
// has reviewed, by `promptReview` per record (spec harder-ghosts, "Review
// samples and prompt counts"). Level 1 is not part of the count.

export const README_START_MARKER = '<!-- prompt-counts:start -->';
export const README_END_MARKER = '<!-- prompt-counts:end -->';

/** The part of a record the count reads. A missing field is not counted. */
export interface CountedRecord {
  promptReview?: string;
}

/** A Level_Dataset keyed by character. */
export type CountedDataset = Readonly<Record<string, CountedRecord>>;

export interface LevelPromptCounts {
  reviewed: number;
  unreviewed: number;
  total: number;
}

export interface PromptCounts {
  level2: LevelPromptCounts;
  level3: LevelPromptCounts;
  reviewed: number;
  unreviewed: number;
  total: number;
}

function countLevel(dataset: CountedDataset): LevelPromptCounts {
  let reviewed = 0;
  let unreviewed = 0;
  for (const record of Object.values(dataset)) {
    if (record.promptReview === 'reviewed') reviewed += 1;
    else if (record.promptReview === 'unreviewed') unreviewed += 1;
  }
  return { reviewed, unreviewed, total: reviewed + unreviewed };
}

/** Counts `promptReview` over the level 2 and level 3 datasets. */
export function computePromptCounts(datasets: {
  level2: CountedDataset;
  level3: CountedDataset;
}): PromptCounts {
  const level2 = countLevel(datasets.level2);
  const level3 = countLevel(datasets.level3);
  return {
    level2,
    level3,
    reviewed: level2.reviewed + level3.reviewed,
    unreviewed: level2.unreviewed + level3.unreviewed,
    total: level2.total + level3.total,
  };
}

function levelLiteral(c: LevelPromptCounts): string {
  return `{ reviewed: ${c.reviewed}, unreviewed: ${c.unreviewed}, total: ${c.total} }`;
}

/** Content of app/src/data/promptCounts.generated.ts. */
export function renderCountsModule(counts: PromptCounts): string {
  return [
    '// Generated by scripts/build-data.ts: generated, do not edit.',
    '// Counts of `promptReview` over the level 2 and level 3 datasets.',
    'export const PROMPT_COUNTS = {',
    `  level2: ${levelLiteral(counts.level2)},`,
    `  level3: ${levelLiteral(counts.level3)},`,
    `  reviewed: ${counts.reviewed},`,
    `  unreviewed: ${counts.unreviewed},`,
    `  total: ${counts.total},`,
    '} as const;',
    '',
  ].join('\n');
}

/** The sentence placed between the README markers. */
export function renderReadmeBlock(counts: PromptCounts): string {
  const l2 = counts.level2;
  const l3 = counts.level3;
  return (
    `Of the ${counts.total} prompts of levels 2 and 3, ${counts.reviewed} are reviewed by a human ` +
    `and ${counts.unreviewed} are not (level 2: ${l2.reviewed} reviewed, ${l2.unreviewed} not; ` +
    `level 3: ${l3.reviewed} reviewed, ${l3.unreviewed} not). ` +
    'A human reviews a random sample of 50 rows per level.'
  );
}

/**
 * Replaces the text between the two README markers with `block`. Throws when
 * a marker is missing or the end marker does not follow the start marker.
 */
export function replaceReadmeBlock(readme: string, block: string): string {
  const start = readme.indexOf(README_START_MARKER);
  if (start === -1) {
    throw new Error(`README.md is missing the marker ${README_START_MARKER}`);
  }
  const end = readme.indexOf(README_END_MARKER, start + README_START_MARKER.length);
  if (end === -1) {
    throw new Error(
      `README.md is missing the marker ${README_END_MARKER} after ${README_START_MARKER}`,
    );
  }
  return (
    readme.slice(0, start + README_START_MARKER.length) +
    '\n' +
    block +
    '\n' +
    readme.slice(end)
  );
}
